export function BrandIcon({ brand, className }: { brand: BrandKey | string; className?: string }) {
  const Cmp = iconMap[brand] || LinkIcon;
  // Dark logos (TikTok, Twitter) are near-black and disappear on dark cards.
  // Render them on a light chip so they're visible in BOTH themes.
  const darkBrand = brand === "tiktok" || brand === "twitter";
  if (darkBrand) {
    return (
      <span className={`inline-flex items-center justify-center rounded-full bg-white p-[2px] dark:bg-white ${className || ""}`}>
        <Cmp className="h-full w-full max-w-full" />
      </span>
    );
  }
  return <Cmp className={className} />;
}
